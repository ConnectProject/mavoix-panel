/* eslint-disable no-await-in-loop -- imports run sequentially to keep tab/item order and avoid flooding the API */
import JSZip from 'jszip'
import Parse from 'parse'

import AssetModel, {
  NAME_KEY as ASSET_NAME_KEY,
  PARSE_FILE_KEY,
  URL_KEY
} from '~/models/Asset'
import TabModel, {
  NAME_KEY as TAB_NAME_KEY,
  HEX_COLOR_KEY,
  ICON_KEY,
  IMAGE_SIZE_KEY,
  LANGUAGE_KEY,
  SPEED_KEY
} from '~/models/Tab'
import TabItemModel, {
  AVAILABLE_KEY,
  HIDDEN_KEY,
  NAME_KEY as ITEM_NAME_KEY,
  ORDER_KEY
} from '~/models/TabItem'
import getCurrentUserId from '~/utils/getCurrentUserId'

const CONFIG_FILE = 'config.json'
const FORMAT_VERSION = 1

const EXTENSIONS = {
  'image/png': 'png',
  'image/jpeg': 'jpg',
  'image/gif': 'gif',
  'image/webp': 'webp',
  'image/svg+xml': 'svg'
}

/**
 * Download an image; resolves null when it cannot be fetched (e.g. CORS).
 * @param {string} url image url
 * @returns {Promise<Blob|null>} image blob or null
 */
const fetchImage = async (url) => {
  try {
    const response = await fetch(url)
    if (!response.ok) {
      return null
    }

    return await response.blob()
  } catch (err) {
    return null
  }
}

/**
 * Build a zip with the global settings, tabs, items and pictures of the current account.
 * @param {{ imageSize: string, ttsSpeed: number, ttsLanguage: string }} globalSettings current global settings
 * @returns {Promise<Blob>} the zip file
 */
export const exportAppConfig = async (globalSettings) => {
  const userId = getCurrentUserId()
  const [tabs, assets] = await Promise.all([
    new Parse.Query(TabModel).equalTo('user', userId)
      .limit(1000)
      .find(),
    new Parse.Query(AssetModel).equalTo('user', userId)
      .limit(1000)
      .find()
  ])
  const items = tabs.length
    ? await new Parse.Query(TabItemModel).containedIn('tab', tabs)
      .ascending(ORDER_KEY)
      .limit(10000)
      .find()
    : []

  const zip = new JSZip()
  const assetsJson = await Promise.all(assets.map(async (asset, index) => {
    const parseFile = asset.get(PARSE_FILE_KEY)
    const url = parseFile ? parseFile.url() : asset.get(URL_KEY)
    const entry = {
      id: asset.id,
      name: asset.get(ASSET_NAME_KEY),
      categories: asset.get('categories') || [],
      url,
      file: null
    }
    const blob = url ? await fetchImage(url) : null
    if (blob) {
      entry.file = `images/${index}.${EXTENSIONS[blob.type] || 'png'}`
      zip.file(entry.file, blob)
    }

    return entry
  }))

  const config = {
    version: FORMAT_VERSION,
    global: {
      imageSize: globalSettings.imageSize,
      ttsSpeed: globalSettings.ttsSpeed,
      ttsLanguage: globalSettings.ttsLanguage
    },
    assets: assetsJson,
    tabs: tabs.map((tab) => ({
      name: tab.get(TAB_NAME_KEY),
      hexColor: tab.get(HEX_COLOR_KEY),
      icon: tab.get(ICON_KEY),
      speed: tab.get(SPEED_KEY),
      language: tab.get(LANGUAGE_KEY),
      imageSize: tab.get(IMAGE_SIZE_KEY),
      items: items
        .filter((item) => item.get('tab').id === tab.id)
        .map((item) => ({
          name: item.get(ITEM_NAME_KEY),
          assetId: item.get('asset') ? item.get('asset').id : null,
          hidden: Boolean(item.get(HIDDEN_KEY)),
          available: item.get(AVAILABLE_KEY) !== false,
          order: item.get(ORDER_KEY)
        }))
    }))
  }
  zip.file(CONFIG_FILE, JSON.stringify(config, null, 2))

  return zip.generateAsync({ type: 'blob' })
}

/**
 * Create the pictures of a configuration for the current account.
 * @param {JSZip} zip loaded zip
 * @param {Object[]} assets assets described in config.json
 * @param {string} userId account id
 * @returns {Promise<Object>} map from exported asset id to the new AssetModel
 */
const importAssets = async (zip, assets, userId) => {
  const created = {}
  for (const [index, entry] of assets.entries()) {
    const zipFile = entry.file && zip.file(entry.file)
    let parseFile = false
    let { url } = entry
    if (zipFile) {
      const ext = entry.file.split('.').pop()
      const blob = await zipFile.async('blob')
      parseFile = await new Parse.File(`import-${Date.now()}-${index}.${ext}`, blob).save()
      url = parseFile.url()
    }
    const asset = AssetModel.New(entry.name, parseFile, url, userId)
    if (entry.categories && entry.categories.length) {
      asset.set('categories', entry.categories)
    }
    created[entry.id] = await asset.save()
  }

  return created
}

/**
 * Read a configuration zip and create its pictures, tabs and items for the current account.
 * Existing tabs and pictures are kept.
 * @param {File} file zip generated by exportAppConfig
 * @returns {Promise<{ global: Object, tabs: number }>} global settings to apply and number of tabs created
 */
export const importAppConfig = async (file) => {
  const zip = await JSZip.loadAsync(file)
  const configFile = zip.file(CONFIG_FILE)
  if (!configFile) {
    throw new Error(`${CONFIG_FILE} not found`)
  }
  const config = JSON.parse(await configFile.async('string'))
  if (config.version !== FORMAT_VERSION || !Array.isArray(config.tabs) || !Array.isArray(config.assets)) {
    throw new Error('Unsupported configuration file')
  }

  const userId = getCurrentUserId()
  const assetsById = await importAssets(zip, config.assets, userId)

  for (const tabData of config.tabs) {
    const tab = await TabModel.New(
      tabData.name, tabData.hexColor, tabData.speed, tabData.language, userId, tabData.icon, tabData.imageSize
    ).save()
    const itemModels = tabData.items
      .filter((item) => assetsById[item.assetId])
      .map((item) => TabItemModel.Create(
        item.name, assetsById[item.assetId], tab, item.hidden, item.available, item.order
      ))
    await Parse.Object.saveAll(itemModels)
  }

  return { global: config.global || {}, tabs: config.tabs.length }
}
